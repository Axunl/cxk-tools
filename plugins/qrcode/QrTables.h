/// 版本号 → 边长（模块数）。v1 = 21，每升一版 +4。
inline int sizeForVersion(int version)
{
    return 17 + 4 * version;
}

/// 边长 → 版本号；不是合法边长时返回 0（调用方据此判定识别失败）。
inline int versionForSize(int size)
{
    if (size < 21 || size > 177 || (size - 17) % 4 != 0)
        return 0;
    return (size - 17) / 4;
}

////
/// 取分块参数。
/// @param version 1–40（越界时钳到边界，不让调用方因为一个坏值直接越界读表）。
///
inline const EccBlockSpec &blocksFor(int version, Ecc ecc)
{
    const int v = qBound(kMinVersion, version, kMaxVersion);
    return kEccBlocks[int(ecc)][v];
}

/// 该版本的**总码字数**（数据 + 纠错），也等于矩阵里能放码字的模块数 / 8。
inline int totalCodewords(int version)
{
    const EccBlockSpec &s = blocksFor(version, Ecc::Low);
    return int(s.blocks1) * (int(s.data1) + int(s.ecPerBlock))
         + int(s.blocks2) * (int(s.data2) + int(s.ecPerBlock));
}

/// 该（版本, 容错等级）能放的数据码字数（byte 模式下还要扣掉模式与长度头）。
inline int totalDataCodewords(int version, Ecc ecc)
{
    const EccBlockSpec &s = blocksFor(version, ecc);
    return int(s.blocks1) * int(s.data1) + int(s.blocks2) * int(s.data2);
}

/// 容量表里每个版本的纠错块数 = blocks1 + blocks2，纠错解码按这个数分块。
inline int blockCount(int version, Ecc ecc)
{
    const EccBlockSpec &s = blocksFor(version, ecc);
    return int(s.blocks1) + int(s.blocks2);
}

/// 格式信息里的 2 位容错等级编码。注意不是枚举值：L=01、M=00、Q=11、H=10。
inline int eccFormatBits(Ecc ecc)
{
    switch (ecc) {
    case Ecc::Low:      return 1;
    case Ecc::Medium:   return 0;
    case Ecc::Quartile: return 3;
    case Ecc::High:     return 2;
    }
    return 0;
}

/// 从格式信息里的 2 位反查容错等级。
inline bool eccFromFormatBits(int bits, Ecc &out)
{
    switch (bits & 0x3) {
    case 1: out = Ecc::Low;      return true;
    case 0: out = Ecc::Medium;   return true;
    case 3: out = Ecc::Quartile; return true;
    case 2: out = Ecc::High;     return true;
    }
    return false;
}

/// 对齐图案的中心坐标（模块坐标）。v1 没有对齐图案，返回的 count 为 0。
inline const int *alignmentPositions(int version, int &count)
{
    const int v = qBound(kMinVersion, version, kMaxVersion);
    count = 0;
    // 表里每行最多 7 个坐标，0 表示结束
    while (count < 7 && kAlignPos[v][count] != 0)
        ++count;
    return kAlignPos[v];
}

/// 容错等级的可读名（界面与日志共用，避免各处自己拼字符串）。
inline QString eccName(Ecc ecc)
{
    switch (ecc) {
    case Ecc::Low:      return QStringLiteral("L");
    case Ecc::Medium:   return QStringLiteral("M");
    case Ecc::Quartile: return QStringLiteral("Q");
    case Ecc::High:     return QStringLiteral("H");
    }
    return QStringLiteral("M");
}

