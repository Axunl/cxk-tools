/// 容错等级。数值顺序就是容量表的下标，别按字母序理解（Q 比 M 高、H 最高）。
enum class Ecc {
    Low = 0,        ///< L：约可恢复 7% 的损坏
    Medium = 1,     ///< M：约 15%
    Quartile = 2,   ///< Q：约 25%
    High = 3,       ///< H：约 30%
};

constexpr int kMinVersion = 1;
constexpr int kMaxVersion = 40;

