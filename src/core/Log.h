#pragma once

// ---------------------------------------------------------------------------
// 日志：把 qInfo/qWarning/qCritical 同时写进 stderr 与文件。
//
// 为什么不用第三方日志库：项目零依赖原则；这里只需要「落盘 + 带时间戳」，
// 一个消息处理器足够，而且插件里的 qWarning 也会自动被收进来，
// 不用给插件再引一套日志接口。
// ---------------------------------------------------------------------------

#include <QString>

class Log
{
public:
    /// 安装全局消息处理器。必须在 QApplication 创建之后、其他部件之前调用，
    /// 否则早期的 qInfo 会走默认处理器（只输出到调试器，不落盘）。
    static void init();

    /// 日志文件绝对路径，方便设置页/错误提示里告诉用户去哪看。
    static QString filePath();
};
